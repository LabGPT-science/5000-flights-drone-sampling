"""Figure: distribution of round-trip flight time per sample, 5,000 simulated flights from the edge lab.

Input:  data/raw/prospera_sim/flights.csv  (generated by simulation/prospera_sim.py)
Output: figures/flight_times.png
"""
import csv
import numpy as np
import matplotlib.pyplot as plt
from config import PROSPERA, FIGURES, GREEN, INK

t = np.array([float(r["water_1L_time_s"]) for r in csv.DictReader(open(PROSPERA / "flights.csv"))]) / 60
fig, ax = plt.subplots(figsize=(7.6, 4.8), dpi=200)
ax.hist(t, bins=np.arange(2.25, 6.6, 0.125), color=GREEN, edgecolor="white", lw=0.4)
med = np.median(t)
ax.axvline(med, color=INK, lw=1.8)
ax.text(med + 0.06, ax.get_ylim()[1] * 0.93, f"median {med:.1f} min", fontsize=11, color=INK)
ax.set_xlabel("Round-trip flight time per sample (minutes)", fontsize=12)
ax.set_ylabel("Number of flights", fontsize=12)
ax.grid(axis="y", color="#E3E8E5"); ax.set_axisbelow(True)
for s in ["top", "right"]:
    ax.spines[s].set_visible(False)
fig.tight_layout(); fig.savefig(FIGURES / "flight_times.png", facecolor="white")
print(f"wrote figures/flight_times.png  (n={len(t)}, median {med:.2f} min, 5–95%: {np.percentile(t,5):.2f}–{np.percentile(t,95):.2f})")
